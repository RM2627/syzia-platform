"""Consolidate existing evidence and list packaged changes against the exact 039 ZIP."""
from pathlib import Path
from datetime import datetime, timezone
import ast
import hashlib
import json
import os
import zipfile

root = Path(__file__).resolve().parents[2]
report_dir = root / 'reports/syzia-040'
docs = root / 'docs/syzia-040'
baseline = root.parents[1] / 'base040/SYZIA-039-Consolidado.zip'
summary = {'round': '040', 'generated_at': datetime.now(timezone.utc).isoformat(), 'suites': []}
for name, filename, count in [('SQL 040', 'sql.json', 35), ('Regressão 038 sobre 040', 'regression-038.json', 22), ('Regressão 039 sobre 040', 'regression-039.json', 26)]:
    results = json.loads((report_dir / filename).read_text())['results']
    assert len(results) == count and all(r['status'] == 'PASS' for r in results)
    summary['suites'].append({'name': name, 'passed': len(results), 'failed': 0, 'evidence': filename})
browser = json.loads((report_dir / 'browser.json').read_text())['stats']
assert browser['expected'] == 9 and not any(browser[k] for k in ['unexpected', 'flaky', 'skipped'])
summary['suites'].append({'name': 'Chromium local', 'passed': browser['expected'], 'failed': 0, 'evidence': 'browser.json'})
assert 'built in' in (report_dir / 'build.log').read_text()
assert 'PASS' in (report_dir / 'bundle.log').read_text()
summary.update(total_passed=sum(s['passed'] for s in summary['suites']), build='PASS', bundle='PASS', external_homologation=False,
    native_postgresql='NOT_EXECUTED: container cannot map required non-root uid',
    independent_connection_concurrency='PENDING: only sequential stale-revision/replay cases executed',
    external_pending=['Owner manual validation and incremental migration in chosen environment', 'Real Auth, SMTP, device sessions and attachment storage/transport', 'Independent PostgreSQL/PostgREST concurrent connections', 'Real billing provider and payment integration'])
integrity = json.loads((report_dir / 'base-integrity.json').read_text())
assert all(i['preserved'] for i in integrity['migrations'] + integrity['brand']) and not integrity['removed']
summary['base_integrity'] = {'base_sha256': integrity['base_sha256'], 'previous_migrations_unchanged': len(integrity['migrations']), 'brand_files_unchanged': len(integrity['brand']), 'removed': 0, 'tables_preserved_on_upgrade': json.loads((report_dir / 'sql.json').read_text())['tablesPreserved']}
(report_dir / 'validation-summary.json').write_text(json.dumps(summary, ensure_ascii=False, indent=2) + '\n')

# Reuse the package exclusions without executing the archiver.
settings = {}
for node in ast.parse((root / 'scripts/package-project.py').read_text()).body:
    if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name) and node.targets[0].id in {'skip_dirs', 'skip_files'}:
        settings[node.targets[0].id] = ast.literal_eval(node.value)
for filename in ['alteracoes.json', 'alteracoes.md']:
    (docs / filename).touch(exist_ok=True)
with zipfile.ZipFile(baseline) as archive:
    before = {n.removeprefix('foundation/'): hashlib.sha256(archive.read(n)).hexdigest() for n in archive.namelist() if n.startswith('foundation/') and not n.endswith('/')}
changes = []
for directory, dirs, names in os.walk(root):
    dirs[:] = sorted(d for d in dirs if d not in settings['skip_dirs'])
    for name in sorted(names):
        if name in settings['skip_files'] or name.endswith(('.dump', '.pyc', '.zip')):
            continue
        if name.startswith('.env') and name not in {'.env.example', '.env.server.example'}:
            continue
        path = Path(directory) / name
        rel = str(path.relative_to(root))
        if rel not in before:
            changes.append({'path': rel, 'status': 'added'})
        elif hashlib.sha256(path.read_bytes()).hexdigest() != before[rel]:
            changes.append({'path': rel, 'status': 'modified'})
changes.sort(key=lambda c: c['path'])
inventory = {'base': 'SYZIA-039-Consolidado.zip', 'base_sha256': integrity['base_sha256'], 'removed': [], 'note': 'MANIFEST.json is regenerated by packaging; it contains final hashes for all packaged files. This inventory excludes the manifest itself.', 'changes': changes}
(docs / 'alteracoes.json').write_text(json.dumps(inventory, ensure_ascii=False, indent=2) + '\n')
counts = {status: sum(c['status'] == status for c in changes) for status in ['modified', 'added']}
lines = ['# SYZIA 040 — inventário de alterações', '', f"Comparação por conteúdo com o consolidado 039: **{counts['modified']} arquivos alterados, {counts['added']} adicionados e nenhum anterior removido**.", '', 'O inventário completo está em `alteracoes.json`. O `MANIFEST.json` da raiz é regenerado no empacotamento e contém os hashes finais. As 36 migrations anteriores, os 23 assets da marca e as dependências/lockfile foram preservados.', '', '## Finalidade das alterações', '', '| Área | Mudança |', '|---|---|', '| Banco | Migration 040 incremental: trial, homologação, destaque, autorização, equipe global e contexto do consumidor. |', '| Frontend | Planos/trial, aplicação de versão, Equipe SYZIA, grants, Central, marca publicada, agenda, FAQ e traduções. |', '| Testes | Suíte 040, regressões 038/039 sobre 040 e navegador; fixture descartável e evidências. |', '| Documentação | Escopo, relatório, upgrade, matrizes, inventário e resumo verificável. |', '| Empacotamento | Nome 040, exclusões dos resultados temporários e manifesto verificável. |', '', '## Arquivos existentes alterados', '']
lines += [f"- `{c['path']}`" for c in changes if c['status'] == 'modified']
lines += ['', '## Arquivos adicionados', '']
aux = [c for c in changes if c['path'].startswith('reports/syzia-040/baseline-functions/')]
lines += [f"- `{c['path']}`" for c in changes if c['status'] == 'added' and c not in aux]
lines += ['', f"Também foram adicionadas {len(aux)} definições SQL em `reports/syzia-040/baseline-functions/`, extraídas da base 039 para diagnóstico e reprodução do gerador da migration. Cada caminho consta no JSON; não são migrations adicionais.", '', 'Os relatórios antigos de build/bundle são atualizados pelo verificador existente. A evidência específica da rodada permanece em `reports/syzia-040/`. Nenhum ambiente externo foi alterado.', '']
(docs / 'alteracoes.md').write_text('\n'.join(lines))
print(json.dumps({'total_passed': summary['total_passed'], **counts, 'removed': 0}, ensure_ascii=False))
